-- ---------- 1. 创建任务表 ----------
create table if not exists public.tasks (
  id          bigint generated by default as identity primary key,
  title       text        not null,                       -- 任务标题
  priority    text        not null default '中',           -- 优先级：高 / 中 / 低
  completed   boolean     not null default false,          -- 完成状态
  created_at  timestamptz not null default now(),          -- 创建时间
  constraint tasks_priority_check check (priority in ('高', '中', '低'))
);

-- ---------- 2. 创建索引（加速按时间倒序查询）----------
create index if not exists tasks_created_at_idx on public.tasks (created_at desc);
create index if not exists tasks_priority_idx   on public.tasks (priority);

-- ---------- 3. 开启行级安全（RLS）----------
alter table public.tasks enable row level security;

-- ---------- 4. 允许匿名读写（课堂项目用，生产环境请收紧）----------
drop policy if exists "allow anon read"   on public.tasks;
drop policy if exists "allow anon insert" on public.tasks;
drop policy if exists "allow anon update" on public.tasks;
drop policy if exists "allow anon delete" on public.tasks;

create policy "allow anon read"
  on public.tasks for select
  to anon
  using (true);

create policy "allow anon insert"
  on public.tasks for insert
  to anon
  with check (true);

create policy "allow anon update"
  on public.tasks for update
  to anon
  using (true)
  with check (true);

create policy "allow anon delete"
  on public.tasks for delete
  to anon
  using (true);

-- ---------- 5. 插入两条示例数据（可选，方便一眼看到效果）----------
insert into public.tasks (title, priority, completed) values
  ('完成低代码实践练习二', '高', false),
  ('把网站部署到 Vercel 并分享给同学', '中', false);
