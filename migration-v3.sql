-- 1) 番茄钟专注记录表（V3.0 新增）
create table if not exists public.pomodoro_sessions (
  id          bigint generated by default as identity primary key,
  started_at  timestamptz not null default now(),
  duration    int not null,                    -- 专注时长（分钟）
  type        text not null default 'focus',  -- focus / short / long
  task_title  text,                            -- 关联任务标题（可选）
  constraint pomodoro_type_check check (type in ('focus', 'short', 'long'))
);

-- 2) 索引：按时间倒序查询
create index if not exists pomodoro_started_at_idx on public.pomodoro_sessions (started_at desc);

-- 3) 开启 RLS（与 tasks 表一致，匿名读写，适合单人项目）
alter table public.pomodoro_sessions enable row level security;

drop policy if exists "allow anon read"   on public.pomodoro_sessions;
drop policy if exists "allow anon insert" on public.pomodoro_sessions;

create policy "allow anon read"
  on public.pomodoro_sessions for select
  to anon using (true);

create policy "allow anon insert"
  on public.pomodoro_sessions for insert
  to anon with check (true);

