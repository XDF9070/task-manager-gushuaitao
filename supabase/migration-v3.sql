-- 安全原则：
--   1. 只做 ADD / CREATE，不做 DROP TABLE、不做 DELETE
--   2. 所有语句可重复执行（幂等），中途失败可再次运行
--   3. 新字段都有默认值，旧数据自动补齐，不会丢失
