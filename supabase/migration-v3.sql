-- ============================================================
-- 四、任务事件表（年度热力图的数据来源）
--    记录"完成/恢复/创建"事件，任务被删除后历史仍可统计
-- ============================================================

create table if not exists public.task_events (
  id         bigint generated by default as identity primary key,
  task_id    bigint,
  type       text not null default 'completed',
  created_at timestamptz not null default now(),
  constraint task_events_type_check check (type in ('created', 'completed', 'reopened'))
);

create index if not exists task_events_time_idx on public.task_events (created_at);
create index if not exists task_events_type_idx on public.task_events (type);

-- 回填历史完成事件：让热力图立刻有内容，而不是从 0 开始
do $$
declare
  done_col text;
  has_completed_at boolean;
begin
  select column_name into done_col
    from information_schema.columns
   where table_schema = 'public'
     and table_name   = 'tasks'
     and column_name in ('is_complete', 'completed')
   limit 1;

  select exists (
    select 1 from information_schema.columns
     where table_schema = 'public' and table_name = 'tasks' and column_name = 'completed_at'
  ) into has_completed_at;

  if done_col is not null and has_completed_at then
    execute format(
      'insert into public.task_events (task_id, type, created_at)
       select t.id, ''completed'', coalesce(t.completed_at, t.created_at)
         from public.tasks t
        where coalesce(t.%I, false) = true
          and not exists (
            select 1 from public.task_events e
             where e.task_id = t.id and e.type = ''completed''
          )',
      done_col
    );
  elsif done_col is not null then
    execute format(
      'insert into public.task_events (task_id, type, created_at)
       select t.id, ''completed'', t.created_at
         from public.tasks t
        where coalesce(t.%I, false) = true
          and not exists (
            select 1 from public.task_events e
             where e.task_id = t.id and e.type = ''completed''
          )',
      done_col
    );
  end if;
end $$;


