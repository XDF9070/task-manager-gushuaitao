-- ============================================================
-- 一、tasks 表扩展（看板状态、重复任务、系列标识）
-- ============================================================

alter table public.tasks add column if not exists status       text;
alter table public.tasks add column if not exists repeat_type  text;
alter table public.tasks add column if not exists repeat_until date;
alter table public.tasks add column if not exists series_id    uuid;

-- 默认值先补上，避免已有行出现 null
alter table public.tasks alter column status      set default 'todo';
alter table public.tasks alter column repeat_type set default 'none';

-- 回填历史数据：已完成的旧任务 → done，未完成 → todo
-- 完成状态列名在不同建表习惯下可能是 is_complete 或 completed，这里动态判断
do $$
declare done_col text;
begin
  select column_name into done_col
    from information_schema.columns
   where table_schema = 'public'
     and table_name   = 'tasks'
     and column_name in ('is_complete', 'completed')
   limit 1;

  if done_col is not null then
    execute format(
      'update public.tasks set status = case when coalesce(%I, false) then ''done'' else ''todo'' end where status is null',
      done_col
    );
  else
    update public.tasks set status = 'todo' where status is null;
  end if;

  update public.tasks set repeat_type = 'none' where repeat_type is null;
end $$;

-- 补上非空约束与取值校验（先判断是否已存在，保证可重复执行）
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'tasks_status_check') then
    alter table public.tasks
      add constraint tasks_status_check check (status in ('todo', 'doing', 'done'));
  end if;

  if not exists (select 1 from pg_constraint where conname = 'tasks_repeat_check') then
    alter table public.tasks
      add constraint tasks_repeat_check check (repeat_type in ('none', 'daily', 'weekly', 'monthly'));
  end if;
end $$;

alter table public.tasks alter column status      set not null;
alter table public.tasks alter column repeat_type set not null;

create index if not exists tasks_status_idx   on public.tasks (status);
create index if not exists tasks_due_date_idx on public.tasks (due_date);
create index if not exists tasks_series_idx   on public.tasks (series_id);


