-- 【重置版】智能任务管理系统 - 重建 tasks 表
-- 用途：如果之前的表字段名不对（比如用了 is_complete），
--       执行本脚本彻底重建，确保字段与代码完全匹配。
--
-- ⚠️ 注意：会删除 tasks 表里所有已有数据！
--    （课堂项目无所谓，重新添加即可）
--
-- 使用方法：Supabase → SQL Editor → New query → 全部粘贴 → Run
-- ============================================================

-- ---------- 1. 删除旧表（如果存在）----------
drop table if exists public.tasks;

-- ---------- 2. 创建任务表（字段与代码完全对应）----------
create table public.tasks (
  id          bigint generated by default as identity primary key,
  title       text        not null,                      -- 任务标题
  priority    text        not null default '中',          -- 优先级：高 / 中 / 低
  completed   boolean     not null default false,         -- 完成状态（代码用的就是这个名字）
  created_at  timestamptz not null default now(),         -- 创建时间
  constraint tasks_priority_check check (priority in ('高', '中', '低'))
);

-- ---------- 3. 索引 ----------
create index tasks_created_at_idx on public.tasks (created_at desc);
create index tasks_priority_idx   on public.tasks (priority);

-- ---------- 4. 开启行级安全 ----------
alter table public.tasks enable row level security;

-- ---------- 5. 允许匿名读写（课堂项目）----------
create policy "allow anon read"
  on public.tasks for select to anon using (true);

create policy "allow anon insert"
  on public.tasks for insert to anon with check (true);

create policy "allow anon update"
  on public.tasks for update to anon using (true) with check (true);

create policy "allow anon delete"
  on public.tasks for delete to anon using (true);

-- ---------- 6. 示例数据 ----------
insert into public.tasks (title, priority, completed) values
  ('完成低代码实践练习二', '高', false),
  ('把网站部署到 Vercel 并分享给同学', '中', false);

-- ---------- 7. 自检：确认字段名 ----------
select column_name, data_type, is_nullable, column_default
from information_schema.columns
where table_schema = 'public' and table_name = 'tasks'
order by ordinal_position;
